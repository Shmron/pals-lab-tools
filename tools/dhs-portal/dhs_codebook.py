# True respondent/household identifiers stripped from any result before it
# reaches the LLM or the client — mirrors ~/PRECISE/api.py's _PRECISE_ID_COLS /
# _strip_id_cols pattern, adapted to DHS's naming.
#
# Deliberately EXCLUDES v001/hv001 (cluster number) and dhsclust: those are the
# standard DHS join key to dhs_ge's GPS coordinates and the whole point of this
# portal is enabling that link — a cluster covers many households, so it is not
# itself respondent-identifying the way a household or case ID is.
DHS_ID_COLS = frozenset({
    'caseid', 'hhid', 'whhid', 'v000', 'hv000',
    'v002', 'v003', 'hv002', 'hv003',   # household number / line number within household
})


_variables = []  # list of dicts, populated by _load()


def _load():
    if not os.path.exists(CODEBOOK_PATH):
        return
    wb = load_workbook(CODEBOOK_PATH, read_only=True, data_only=True)
    for code in RECODES:
        if code not in wb.sheetnames:
            continue
        ws = wb[code]
        rows = ws.iter_rows(min_row=5, values_only=True)  # header is row 4
        for row in rows:
            if not row or not row[0]:
                continue
            variable = str(row[0]).strip()
            if variable.lower().startswith('total columns'):
                break  # hit the footer row
            _variables.append({
                'recode':   code,
                'table':    RECODES[code][1],
                'variable': variable,
                'label':    str(row[1]).strip() if len(row) > 1 and row[1] else '',
                'dtype':    str(row[2]).strip() if len(row) > 2 and row[2] else '',
                'pct_nonnull': str(row[3]).strip() if len(row) > 3 and row[3] else '',
                'examples': str(row[4]).strip() if len(row) > 4 and row[4] else '',
            })
    wb.close()


def search_variables(keyword, limit=20):
    """Case-insensitive search over variable name + label/description.
    Exact/prefix variable-name matches rank above label-only matches."""
    if not keyword or not keyword.strip():
        return []
    kw = keyword.strip().lower()
    exact, prefix, contains, label_only = [], [], [], []
    for v in _variables:
        var_l = v['variable'].lower()
        lab_l = v['label'].lower()
        if var_l == kw:
            exact.append(v)
        elif var_l.startswith(kw):
            prefix.append(v)
        elif kw in var_l:
            contains.append(v)
        elif kw in lab_l:
            label_only.append(v)
    ranked = exact + prefix + contains + label_only
    return ranked[:limit]


def module_map_text():
    """Short table/module map for the chat system prompt — deliberately NOT a
    full column dump (some tables have 60,000+ columns)."""
    lines = []
    for code, (dbfile, table, title, desc) in RECODES.items():
        lines.append(f"- {code} ({table}): {title} — {desc}")
    return '\n'.join(lines)


_load()
